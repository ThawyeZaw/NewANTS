export function createPresetTimetableState(
  presetId: TimetablePresetId = 'workday-coaching',
  referenceDate: string = DEFAULT_TIMETABLE_REFERENCE_DATE
): TimetablePersistedState {
  if (presetId === 'scholar-ial') {
    return {
      version: 1,
      presetId: 'scholar-ial',
      viewMode: 'week',
      selectedDate: referenceDate,
      showExams: true,
      showOvernightHours: false,
      telegramConnected: false,
      telegramHandle: '',
      blocks: createScholarBlocks(referenceDate),
      focusTasks: createScholarFocusTasks(),
    };
  }
  return {
    version: 1,
    presetId: 'workday-coaching',
    viewMode: 'week',
    selectedDate: referenceDate,
    showExams: true,
    showOvernightHours: false,
    telegramConnected: false,
    telegramHandle: '',
    blocks: createCoachingBlocks(referenceDate),
    focusTasks: createCoachingFocusTasks(),
  };
}

